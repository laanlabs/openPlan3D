/** Preserve variable glTF identifiers and unknown external decoder diagnostics. */
export function customModelError(message: string, language: Locale): string {
  if (Object.hasOwn(customModelMessages, message)) return translate(language, customModelMessages[message]);
  const patterns: [RegExp, TranslationKey][] = [
    [/^Invalid GLB geometry: Unsupported format for ([\s\S]*)\.$/, 'customModelValidation.attributeFormat'],
    [/^Unsupported GLB extension: ([\s\S]*) is not supported by local model import yet\.$/, 'customModelValidation.unsupportedExtension'],
    [/^Unsupported GLB extension: ([\s\S]*) is missing from extensionsUsed\.$/, 'customModelValidation.undeclaredExtension'],
  ];
  for (const [pattern, key] of patterns) {
    const match = pattern.exec(message);
    if (match) return translate(language, key, { name: match[1] });
  }
  return message;
}
